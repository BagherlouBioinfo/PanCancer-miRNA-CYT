# Run with Rscript test_stage25.R <package-directory>, or source in RStudio.
package_dir <- file.path(project_root,"scripts/lib")
source(file.path(package_dir,"stage25_external_validation.R"), local=TRUE)
test_n <- 0L
check <- function(name, expr) {
  test_n <<- test_n + 1L
  if (!isTRUE(expr)) stop("[FAIL] ", name)
  cat("[PASS] ", name, "\n", sep = "")
}
raises <- function(expr) inherits(tryCatch({ force(expr); NULL }, error = identity), "error")
set.seed(2718)
x <- rnorm(100); y <- .7 * x + rnorm(100)
fit <- s25_cor(x, y, 30)
ref <- suppressWarnings(cor.test(x, y, method = "spearman", exact = FALSE))
check("Spearman matches cor.test", abs(fit$rho - unname(ref$estimate)) < 1e-12 && abs(fit$p_raw - ref$p.value) < 1e-10)
xx <- c(x, NA, Inf); yy <- c(y, 100, -200)
check("Non-finite observations excluded before ranking", identical(s25_cor(xx, yy, 30), fit))
check("Insufficient samples are not nonsignificant results", s25_cor(x[1:20], y[1:20], 30)$status == "insufficient_complete_samples" && is.na(s25_cor(x[1:20], y[1:20], 30)$p_raw))
check("Constant features rejected", s25_cor(rep(1, 100), y, 30)$status == "zero_variance")
check("Perfect negative relationship retained", s25_cor(1:100, -(1:100), 30)$rho == -1)
check("Invalid boolean rejected", raises(s25_bool(c("TRUE", "garbage"))))
check("Boolean missingness does not select rows", identical(s25_bool(c("TRUE", "FALSE", NA)), c(TRUE, FALSE, FALSE)))
check("Duplicate hypothesis keys rejected", raises(s25_unique(data.frame(m = c("a", "a"), g = c("x", "x")), c("m", "g"), "test")))
q <- s25_family_adjust(c(.001, NA, .02), 47)
check("Missing hypotheses stay in planned BH family", is.na(q[2]) && max(abs(q[c(1, 3)] - p.adjust(c(.001, .02), method = "BH", n = 47))) < 1e-12)
check("BY sensitivity is not smaller than BH", all(s25_family_adjust(c(.001, .02), 47, "BY") >= s25_family_adjust(c(.001, .02), 47)))
z <- rnorm(100); a <- z + rnorm(100); b <- z + rnorm(100)
pr <- s25_cor(a, b, 30, z)
ar <- rank(s25_winsor(a, c(.001, .999))); br <- rank(s25_winsor(b, c(.001, .999))); zr <- rank(s25_winsor(z, c(.001, .999)))
expected <- cor(resid(lm(ar ~ zr)), resid(lm(br ~ zr)))
check("Partial Spearman matches independent rank residual refit", abs(pr$rho - expected) < 1e-12)
check("Constant adjustment cannot be reported as adjusted", s25_cor(a, b, 30, rep(1, 100))$status == "zero_variance_covariate")
check("Empty external features are non-estimable", s25_cor(rep(NA_real_, 100), y, 30)$n == 0L)
check("Winsorisation preserves missingness", is.na(s25_winsor(c(1:100, NA), c(.001, .999))[101]))
if (requireNamespace("data.table", quietly = TRUE)) {
  cfg <- list(expected_primary_pairs = 2L, rho_threshold = .30, discovery_run_id = "test")
  tmp <- tempfile(fileext = ".tsv")
  fake <- data.frame(mirna_id = c("a", "b", "c"), gene = c("x", "y", "z"), qualifies = c(TRUE, FALSE, TRUE), strict_recurrence = c(3L, 0L, 4L), purity_setting = "CPE", threshold = .30, run_id = "test")
  s25_write(fake, tmp)
  p <- s25_primary(tmp, cfg)
  check("Only qualifies TRUE rows frozen", identical(p$mirna_id, c("a", "c")))
  fake$run_id[1] <- "other_run"; s25_write(fake, tmp)
  check("Mixed discovery runs rejected", raises(s25_primary(tmp, cfg)))
  unlink(tmp)
} else cat("[SKIP] two file-based tests: data.table unavailable\n")
cat("\n", test_n, " checks PASS\n", sep = "")
