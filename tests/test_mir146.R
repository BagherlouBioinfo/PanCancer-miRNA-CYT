if(!exists('code_root')) code_root<-getwd()
source(file.path(code_root,'context_reader.R'));source(file.path(code_root,'mir146_analysis.R'))
passed<-0L
check<-function(x,label) {if(!isTRUE(x)) stop('[FAIL] ',label);passed<<-passed+1L;cat('[PASS] ',label,'\n',sep='')}
set.seed(9816);n<-800;a<-rnorm(n);b<-.5*a+rnorm(n);p<-runif(n);y<-.7*a+.6*b+.5*p+rnorm(n)
f<-m146_fit(y,a,b,p)
check(f$status=='ESTIMATED','complementary synthetic model estimable')
check(all(f$effects$p_HC3<.001),'both synthetic effects detected')
check(all(f$effects$beta_rank>0),'known effect directions recovered')
d<-data.frame(y=m146_rank(y),a=m146_rank(a),b=m146_rank(b),p=m146_rank(p))
fit<-lm(y~a+b+p,d);X<-model.matrix(fit);bread<-solve(t(X)%*%X)
meat<-Reduce(`+`,lapply(seq_len(n),function(i) tcrossprod(X[i,])*resid(fit)[i]^2/(1-hatvalues(fit)[i])^2))
V<-bread%*%meat%*%bread
check(max(abs(f$effects$HC3_se-sqrt(diag(V))[c('a','b')]))<1e-10,'HC3 covariance matches independent row-wise calculation')
ry<-resid(lm(y~b+p,d));ra<-resid(lm(a~b+p,d))
check(abs(f$effects[focal=='a']$partial_rho-cor(ry,ra))<1e-12,'partial rank correlation matches independent residual calculation')
check(abs(f$effects[focal=='a']$delta_R2-(summary(fit)$r.squared-summary(lm(y~b+p,d))$r.squared))<1e-12,'delta R2 matches direct nested fits')
check(all(f$effects$delta_R2>=0),'incremental in-sample R2 nonnegative')
check(m146_fit(y,a,a,p)$status=='NOT_ESTIMABLE','identical miRNAs rejected as unidentifiable')
check(m146_fit(y,a,b,rep(.5,n))$status=='NOT_ESTIMABLE','constant purity cannot masquerade as adjustment')
check(m146_fit(y[1:20],a[1:20],b[1:20],p[1:20])$status=='NOT_ESTIMABLE','minimum sample requirement')
y2<-y;y2[1]<-NA;a2<-a;a2[2]<-Inf
q<-m146_fit(y2,a2,b,p)
check(q$n==n-2 && all(!1:2%in%q$keep),'joint complete cases exclude nonfinite observations')
check(inherits(try(m146_fit(y[-1],a,b,p),silent=TRUE),'try-error'),'unequal vectors rejected')
x<-data.table(mirna_id=c('A','B'),S2=c(2,4),S1=c(1,3))
z<-m146_extract(x,'mirna_id',c('B','A'),c('S1','S2'))
check(identical(as.numeric(z['B',]),c(3,4)),'expression extraction preserves requested sample order')
check(inherits(try(m146_extract(rbind(x,x[1]),'mirna_id','A',c('S1','S2')),silent=TRUE),'try-error'),'duplicate expression ID rejected')
check(inherits(try(m146_extract(x,'mirna_id','C',c('S1','S2')),silent=TRUE),'try-error'),'missing expression feature rejected')
cat('\n',passed,' tests PASS\n',sep='')
